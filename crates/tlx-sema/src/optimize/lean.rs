//! Standalone Lean algebra, transformation records and optional rule-IR certificates.
//! Rust lowering and runtime execution remain outside the proof boundary.

use std::fmt::Write;

use crate::{hir::Expr, Program};
use tlx_front::cfg::Config;

/// Emit without running Lean. The library is embedded so the output needs no
/// tlx checkout, network access, Lake project, or generated import search path.
pub fn projection_lean(
    program: &Program,
    cfg: &Config,
    rule: Option<&str>,
    fields: &[String],
    view: Option<&Expr>,
    certificate: Option<&str>,
    ordered: Option<&super::OrderedPlan>,
) -> String {
    let mut out = String::from(
        "-- Generated by tlx. Lean was NOT run.\n\
         -- Coverage: shared rule algebra, plus a transformation record.\n\
         -- Model applicability and TLA+/HIR semantics are NOT certified here.\n\
         -- No model-level Certificate is constructed.\n\n",
    );
    if certificate.is_some() {
        out = String::from(
            "-- Generated by tlx. Lean was NOT run.\n\
             -- Coverage: parametric rule-IR certificate.\n\
             -- HIR lowering, totality and runtime remain trusted; uncertified projection/symmetry combinations stay gated.\n\n",
        );
    }
    out.push_str(include_str!("Rules.lean"));
    out.push_str(include_str!("Age.lean"));
    out.push_str(include_str!("Ordered.lean"));
    out.push_str("\nnamespace TlxOptimization.Generated\n");
    for (name, value) in [
        ("rule", rule.unwrap_or("none").to_string()),
        ("fields", fields.join(", ")),
        (
            "arithmeticSemantics",
            match rule {
                Some("relative-age-projection") => "Mathematical natural-number clocks; eventual machine overflow need not be preserved.",
                Some("ordered-allocation-projection") => {
                    "Mathematical natural-number allocation; eventual machine overflow need not be preserved."
                }
                _ => "Checked machine arithmetic.",
            }
            .to_string(),
        ),
        ("configuration", format!("{cfg:#?}")),
        ("variables", format!("{:#?}", program.vars)),
        ("constants", format!("{:#?}", program.consts)),
        ("beforeHIR", format!("{:#?}", program.defs)),
        ("afterViewHIR", format!("{view:#?}")),
        ("structuralOrderPlan", format!("{ordered:#?}")),
        (
            "projectionMechanism",
            if rule == Some("keyed-symmetry") {
                if certificate.is_some_and(|c| c.contains("namespace TlxOptimization.GeneratedEquivSymmetry")) {
                    "The certified full key-permutation group is closed and canonicalized at the fingerprint boundary via generic equivariant value symmetry."
                } else {
                    "The certified full key-permutation group is closed and canonicalized at the fingerprint boundary."
                }
            } else if ordered.is_some() {
                "The structuralOrderPlan replaces the identity afterViewHIR at the fingerprint boundary."
            } else {
                "The afterViewHIR expression is evaluated at the fingerprint boundary."
            }
            .to_string(),
        ),
    ] {
        writeln!(out, "def {name} : String := {}\n", literal(&value)).unwrap();
    }
    for (i, file) in program.files.iter().enumerate() {
        writeln!(out, "def file{i}Path : String := {}", literal(&file.path.to_string_lossy())).unwrap();
        writeln!(out, "def file{i}Source : String := {}\n", literal(&file.src)).unwrap();
    }
    out.push_str("end TlxOptimization.Generated\n");
    if let Some(certificate) = certificate {
        out.push_str(certificate);
    }
    out
}

// Lean uses fixed-width hexadecimal escapes, unlike Rust's \u{...}. Escape
// source text as data; a model cannot inject declarations into the proof file.
pub(super) fn literal(s: &str) -> String {
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if c.is_control() => write!(out, "\\u{:04x}", c as u32).unwrap(),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn source_is_escaped_as_lean_data() {
        assert_eq!(literal("\"\nend Injected\\\t\r\0λ"), "\"\\\"\\nend Injected\\\\\\t\\r\\u0000λ\"");
    }
}
